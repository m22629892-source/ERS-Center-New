let i18nContent = fs.readFileSync('i18n.ts', 'utf8');

for (const lang of Object.keys(translations)) {
  const dict = translations[lang];
  const langKey = `${lang}: {`;
  const idx = i18nContent.indexOf(langKey);
  if (idx === -1) {
    console.error(`Language key ${langKey} not found!`);
    continue;
  }

  // Find translation: {
  const transKey = 'translation: {';
  const transIdx = i18nContent.indexOf(transKey, idx);
  if (transIdx === -1) {
    console.error(`translation: { not found for ${lang}`);
    continue;
  }

  const insertionPoint = transIdx + transKey.length;

  // Build key-value entries to insert
  let insertText = '\n';
  for (const [k, v] of Object.entries(dict)) {
    // Only insert if not already present in the block
    const escapedV = JSON.stringify(v);
    insertText += `      "${k}": ${escapedV},\n`;
  }

  i18nContent = i18nContent.slice(0, insertionPoint) + insertText + i18nContent.slice(insertionPoint);
  console.log(`Injected ${Object.keys(dict).length} keys for language [${lang}]`);
}

fs.writeFileSync('i18n.ts', i18nContent, 'utf8');
